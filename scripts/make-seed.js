// data/db.json (from the Excel workbook) -> supabase/seed.sql, to paste into the Supabase SQL editor once.
// Usage: node scripts/make-seed.js owner@example.com [building-id] [building name]
// Loads the data as one building (default id 1). To add another building later, run with a different id.
// The output contains personal data. It is git-ignored: never commit or share it.
const fs = require('fs');
const path = require('path');
const { snapshot } = require('../lib/snapshot');

const owner = (process.argv[2] || '').trim().toLowerCase();
if (!/^\S+@\S+\.\S+$/.test(owner)) { console.error('usage: node scripts/make-seed.js owner@example.com'); process.exit(1); }
const B = Number(process.argv[3] || 1);
const db = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'data', 'db.json'), 'utf8'));

const q = (v) => (v === null || v === undefined || v === '' ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const j = (o) => `'${JSON.stringify(o).replace(/'/g, "''")}'::jsonb`;
const ins = (table, cols, rows) => {
  if (!rows.length) return '';
  cols = ['building_id', ...cols]; rows = rows.map((r) => [String(B), ...r]);
  let s = '';
  for (let i = 0; i < rows.length; i += 200) {
    s += `insert into public.${table} (${cols.join(', ')}) values\n` + rows.slice(i, i + 200).map((r) => `  (${r.join(', ')})`).join(',\n') + ';\n';
  }
  return s;
};

let sql = '-- generated by scripts/make-seed.js — contains personal data, do not commit\nbegin;\n';
const bname = process.argv[4] || db.settings.title || 'ועד הבית';
sql += `insert into public.buildings (id, name) values (${B}, ${q(bname)}) on conflict (id) do update set name = excluded.name;\n`;
sql += ins('apartments', ['apt', 'floor', 'rooms', 'sqm'], db.apartments.map((a) => [q(a.apt), q(a.floor), q(a.rooms), q(a.sqm)]));
sql += ins('residents', ['key', 'apt', 'first_name', 'last_name', 'first2', 'last2', 'phone1', 'phone2', 'role', 'status', 'entry_month', 'entry_year', 'exit_month', 'exit_year', 'account'],
  db.residents.map((r) => [q(r.key), q(r.apt), q(r.first), q(r.last), q(r.first2), q(r.last2), q(r.phone1), q(r.phone2), q(r.role), q(r.status), q(r.entryMonth), q(r.entryYear), q(r.exitMonth), q(r.exitYear), q(r.account)]));
sql += ins('owners', ['apt', 'first_name', 'last_name', 'phone', 'account', 'note'], db.owners.map((o) => [q(o.apt), q(o.first), q(o.last), q(o.phone), q(o.account), q(o.note)]));
sql += ins('tariffs', ['year', 'month', 'apt', 'amount', 'note'], db.tariffs.map((t) => [q(t.year), q(t.month), q(t.apt), q(t.amount), q(t.note)]));
sql += ins('payments', ['key', 'apt', 'y', 'm', 'amount', 'method', 'paid_on', 'note', 'ref', 'src', 'tx_key'],
  db.payments.map((p) => [q(p.key), q(p.apt), q(p.y), q(p.m), q(p.amount), q(p.method), q(p.date), q(p.note), q(p.ref), q(p.src), q(p.txKey)]));
sql += ins('expenses', ['y', 'm', 'd', 'category', 'descr', 'amount', 'method', 'note'], db.expenses.map((e) => [q(e.y), q(e.m), q(e.d), q(e.category), q(e.desc), q(e.amount), q(e.method), q(e.note)]));
for (const name of ['bankSeen', 'refSeen', 'aliases', 'ignored', 'settings']) {
  sql += `insert into public.meta (building_id, name, value) values (${B}, ${q(name)}, ${j(db[name])}) on conflict (building_id, name) do update set value = excluded.value;\n`;
}
sql += `insert into public.members (building_id, email, role, name) values (${B}, ${q(owner)}, 'owner', 'בעל הבית') on conflict (building_id, email) do update set role = 'owner';\n`;
sql += `insert into public.snapshot (building_id, data) values (${B}, ${j(snapshot(db))}) on conflict (building_id) do update set data = excluded.data, updated_at = now();\n`;
sql += `select setval(pg_get_serial_sequence('public.buildings', 'id'), (select max(id) from public.buildings));\n`;
sql += 'commit;\n';

fs.writeFileSync(path.join(__dirname, '..', 'supabase', 'seed.sql'), sql);
console.log(`supabase/seed.sql written (${Math.round(sql.length / 1024)} KB), owner: ${owner}, building ${B}`);
