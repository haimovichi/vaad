// Bundle lib/*.js (CommonJS) into app/vaad-lib.js for the browser — no build tooling needed.
const fs = require('fs');
const path = require('path');

const mods = ['calc', 'bank', 'match', 'snapshot', 'service'];
let out = '// generated by scripts/build-app.js — do not edit\n(function () {\nconst defs = {}; const cache = {};\n';
out += "function load(k) { if (cache[k]) return cache[k].exports; const m = { exports: {} }; cache[k] = m; defs[k](m, m.exports, function (p) { return p === 'xlsx' ? window.XLSX : load(p.replace(/^\\.\\//, '').replace(/\\.js$/, '')); }); return m.exports; }\n";
for (const m of mods) {
  const src = fs.readFileSync(path.join(__dirname, '..', 'lib', `${m}.js`), 'utf8');
  out += `defs['${m}'] = function (module, exports, require) {\n${src}\n};\n`;
}
out += "window.VaadLib = { calc: load('calc'), snapshot: load('snapshot'), service: load('service') };\n})();\n";
fs.writeFileSync(path.join(__dirname, '..', 'app', 'vaad-lib.js'), out);
console.log('app/vaad-lib.js built');
