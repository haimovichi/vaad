-- ועד הבית — multi-building schema + role-based security.
-- Run once in Supabase: SQL Editor -> New query -> paste -> Run.
--
-- Every row belongs to a building (building_id). A person's role is per building (table public.members):
--   owner  : full access to that building (import bank files, edit, manage users, control the tenant view)
--   admin  : read-only access to everything in that building (including phones and bank descriptions)
--   tenant : read-only access to that building's tenant snapshot only (no phones, no accounts, no bank rows)
-- An email can belong to several buildings with different roles. Unlisted emails can read nothing.
-- New buildings are created by the platform operator (SQL editor), see README.

create table if not exists public.buildings (
  id   bigint generated by default as identity primary key,
  name text not null
);

create table if not exists public.members (
  building_id bigint not null references public.buildings(id) on delete cascade,
  email text not null check (email = lower(email)),
  role  text not null check (role in ('owner','admin','tenant')),
  apt   int,
  name  text,
  primary key (building_id, email)
);
create index if not exists members_email_idx on public.members(email);

create table if not exists public.apartments (
  building_id bigint not null references public.buildings(id) on delete cascade,
  apt int not null, floor text, rooms int, sqm int,
  primary key (building_id, apt)
);

create table if not exists public.residents (
  id bigint generated always as identity primary key,
  building_id bigint not null references public.buildings(id) on delete cascade,
  key text not null,
  apt int not null,
  first_name text, last_name text, first2 text, last2 text,
  phone1 text, phone2 text, role text, status text,
  entry_month int, entry_year int, exit_month int, exit_year int,
  account text,
  unique (building_id, key),
  foreign key (building_id, apt) references public.apartments(building_id, apt)
);

create table if not exists public.owners (
  id bigint generated always as identity primary key,
  building_id bigint not null references public.buildings(id) on delete cascade,
  apt int not null,
  first_name text, last_name text, phone text, account text, note text,
  foreign key (building_id, apt) references public.apartments(building_id, apt)
);

create table if not exists public.tariffs (
  id bigint generated always as identity primary key,
  building_id bigint not null references public.buildings(id) on delete cascade,
  year int not null, month int, apt int, amount numeric not null, note text
);

create table if not exists public.payments (
  id bigint generated always as identity primary key,
  building_id bigint not null references public.buildings(id) on delete cascade,
  key text not null,           -- tenancy key (residents.key)
  apt int not null,
  y int not null, m int not null,
  amount numeric not null,
  method text, paid_on date, note text, ref text, src text, tx_key text
);
create index if not exists payments_key_idx on public.payments(building_id, key);

create table if not exists public.expenses (
  id bigint generated always as identity primary key,
  building_id bigint not null references public.buildings(id) on delete cascade,
  y int, m int, d int, category text, descr text, amount numeric, method text, note text
);

-- bankSeen / refSeen / aliases / ignored / settings
create table if not exists public.meta (
  building_id bigint not null references public.buildings(id) on delete cascade,
  name text not null, value jsonb not null default '{}'::jsonb,
  primary key (building_id, name)
);

-- what tenants see: allow-listed statuses only, written by the owner's app
create table if not exists public.snapshot (
  building_id bigint primary key references public.buildings(id) on delete cascade,
  data jsonb not null,
  updated_at timestamptz not null default now()
);

-- ---------- role helper: the caller's role in one building ----------
create or replace function public.app_role(b bigint) returns text
language sql stable security definer set search_path = public as $$
  select role from public.members
  where building_id = b and email = lower(coalesce(auth.jwt() ->> 'email', '')) limit 1
$$;
revoke all on function public.app_role(bigint) from public, anon;
grant execute on function public.app_role(bigint) to authenticated;

-- ---------- own-apartment payments (what a tenant may see about their own payments) ----------
-- Returns only month, amount, method and date. Never notes, bank descriptions, references or other tenants.
-- tenant: only their own apartment (members.apt) and only the current tenancy; owner/admin: any apartment.
create or replace function public.apt_payments(b bigint, a int, yr int)
returns table (y int, m int, amount numeric, method text, paid_on date)
language sql stable security definer set search_path = public as $$
  select p.y, p.m, p.amount, p.method, p.paid_on
  from public.payments p
  where p.building_id = b and p.apt = a and p.y = yr
    and (
      public.app_role(b) in ('owner', 'admin')
      or (
        public.app_role(b) = 'tenant'
        and exists (select 1 from public.members mm
                    where mm.building_id = b and mm.apt = a
                      and mm.email = lower(coalesce(auth.jwt() ->> 'email', '')))
        and exists (select 1 from public.residents r
                    where r.building_id = b and r.key = p.key and coalesce(r.status, '') <> 'עזב')
      )
    )
  order by p.m, p.paid_on
$$;
revoke all on function public.apt_payments(bigint, int, int) from public, anon;
grant execute on function public.apt_payments(bigint, int, int) to authenticated;

-- ---------- row level security ----------
alter table public.buildings  enable row level security;
alter table public.members    enable row level security;
alter table public.apartments enable row level security;
alter table public.residents  enable row level security;
alter table public.owners     enable row level security;
alter table public.tariffs    enable row level security;
alter table public.payments   enable row level security;
alter table public.expenses   enable row level security;
alter table public.meta       enable row level security;
alter table public.snapshot   enable row level security;

revoke all on all tables in schema public from anon;

-- staff data: a building's owner + admin read, its owner writes
do $$
declare t text;
begin
  foreach t in array array['apartments','residents','owners','tariffs','payments','expenses','meta'] loop
    execute format('drop policy if exists staff_read on public.%I', t);
    execute format('drop policy if exists owner_write on public.%I', t);
    execute format($p$create policy staff_read on public.%I for select to authenticated using (public.app_role(building_id) in ('owner','admin'))$p$, t);
    execute format($p$create policy owner_write on public.%I for all to authenticated using (public.app_role(building_id) = 'owner') with check (public.app_role(building_id) = 'owner')$p$, t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;

-- buildings: members see their buildings; only an owner can rename; creating/deleting is platform-only (SQL editor)
drop policy if exists member_read on public.buildings;
drop policy if exists owner_update on public.buildings;
create policy member_read  on public.buildings for select to authenticated using (public.app_role(id) is not null);
create policy owner_update on public.buildings for update to authenticated using (public.app_role(id) = 'owner') with check (public.app_role(id) = 'owner');
grant select, update on public.buildings to authenticated;

-- members: everyone reads their own rows, an owner reads and writes their building's rows
drop policy if exists own_row on public.members;
drop policy if exists owner_all on public.members;
create policy own_row   on public.members for select to authenticated using (email = lower(coalesce(auth.jwt() ->> 'email', '')));
create policy owner_all on public.members for all    to authenticated using (public.app_role(building_id) = 'owner') with check (public.app_role(building_id) = 'owner');
grant select, insert, update, delete on public.members to authenticated;

-- snapshot: any member of the building reads, its owner writes
drop policy if exists member_read on public.snapshot;
drop policy if exists owner_write on public.snapshot;
create policy member_read on public.snapshot for select to authenticated using (public.app_role(building_id) in ('owner','admin','tenant'));
create policy owner_write on public.snapshot for all    to authenticated using (public.app_role(building_id) = 'owner') with check (public.app_role(building_id) = 'owner');
grant select, insert, update, delete on public.snapshot to authenticated;

grant usage on all sequences in schema public to authenticated;
