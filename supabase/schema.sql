-- ועד הבית — schema + role-based security (multi-building, five roles).
-- Run in Supabase: SQL Editor -> New query -> paste -> Run. Safe to re-run (idempotent).
-- Upgrading from the earlier owner/admin/tenant version? Run supabase/migrate-roles.sql first, then this file.
--
-- ROLES
--   super user        : exactly one person, set only in the SQL editor (table super_users). Can do anything, in every building.
--   buildings manager : table managers + manager_buildings. Manages the buildings assigned to them and can create new ones.
--   building committee: members.role = 'committee'. Manages one building (bank import, payments, tenants, backup...).
--   tenant            : members.role = 'tenant' (+ apt). Sees the building board; payment details only for their own apartment.
--   apartment owner   : members.role = 'apt_owner' (+ apt). Sees only their apartments: status, the current tenant's
--                       payments with dates, and the tenant's name and phones.
-- A person can hold any mix of roles; they combine (union of what each allows).
--
-- WHO CAN GRANT WHAT (enforced on public.members)
--   super user: any building, committee/tenant/apt_owner (and managers, in the app)
--   manager   : committee/tenant/apt_owner in the buildings they manage
--   committee : tenant/apt_owner in their own building

create table if not exists public.buildings (
  id   bigint generated by default as identity primary key,
  name text not null
);

-- platform level --------------------------------------------------------------------------------
create table if not exists public.super_users (
  email text primary key check (email = lower(email))
);
create unique index if not exists super_users_one_row on public.super_users ((true));  -- at most one super user, ever

create table if not exists public.managers (
  email text primary key check (email = lower(email))
);
create table if not exists public.manager_buildings (
  building_id bigint not null references public.buildings(id) on delete cascade,
  email text not null references public.managers(email) on delete cascade,
  primary key (building_id, email)
);

-- building level --------------------------------------------------------------------------------
create table if not exists public.members (
  id bigint generated always as identity primary key,
  building_id bigint not null references public.buildings(id) on delete cascade,
  email text not null check (email = lower(email)),
  role  text not null,
  apt   int,
  name  text
);
alter table public.members drop constraint if exists members_role_check;
alter table public.members add  constraint members_role_check check (role in ('committee','tenant','apt_owner'));
alter table public.members drop constraint if exists members_apt_owner_apt;
alter table public.members add  constraint members_apt_owner_apt check (role <> 'apt_owner' or apt is not null);
alter table public.members drop constraint if exists members_committee_no_apt;
alter table public.members add  constraint members_committee_no_apt check (role <> 'committee' or apt is null);
create unique index if not exists members_unique on public.members (building_id, email, role, coalesce(apt, 0));
create index if not exists members_email_idx on public.members(email);

create table if not exists public.apartments (
  building_id bigint not null references public.buildings(id) on delete cascade,
  apt int not null, floor text, rooms int, sqm int,
  primary key (building_id, apt)
);

create table if not exists public.residents (
  id bigint generated always as identity primary key,
  building_id bigint not null references public.buildings(id) on delete cascade,
  key text not null,
  apt int not null,
  first_name text, last_name text, first2 text, last2 text,
  phone1 text, phone2 text, role text, status text,
  entry_month int, entry_year int, exit_month int, exit_year int,
  account text,
  unique (building_id, key),
  foreign key (building_id, apt) references public.apartments(building_id, apt)
);

create table if not exists public.owners (
  id bigint generated always as identity primary key,
  building_id bigint not null references public.buildings(id) on delete cascade,
  apt int not null,
  first_name text, last_name text, phone text, account text, note text,
  foreign key (building_id, apt) references public.apartments(building_id, apt)
);

create table if not exists public.tariffs (
  id bigint generated always as identity primary key,
  building_id bigint not null references public.buildings(id) on delete cascade,
  year int not null, month int, apt int, amount numeric not null, note text
);

create table if not exists public.payments (
  id bigint generated always as identity primary key,
  building_id bigint not null references public.buildings(id) on delete cascade,
  key text not null,           -- tenancy key (residents.key)
  apt int not null,
  y int not null, m int not null,
  amount numeric not null,
  method text, paid_on date, note text, ref text, src text, tx_key text
);
create index if not exists payments_key_idx on public.payments(building_id, key);

create table if not exists public.expenses (
  id bigint generated always as identity primary key,
  building_id bigint not null references public.buildings(id) on delete cascade,
  y int, m int, d int, category text, descr text, amount numeric, method text, note text
);

-- bankSeen / refSeen / aliases / ignored / settings
create table if not exists public.meta (
  building_id bigint not null references public.buildings(id) on delete cascade,
  name text not null, value jsonb not null default '{}'::jsonb,
  primary key (building_id, name)
);

-- what tenants see: allow-listed statuses only, written by the committee's app
create table if not exists public.snapshot (
  building_id bigint primary key references public.buildings(id) on delete cascade,
  data jsonb not null,
  updated_at timestamptz not null default now()
);

-- ---------- who is calling ----------
create or replace function public.me() returns text
language sql stable set search_path = public as $$ select lower(coalesce(auth.jwt() ->> 'email', '')) $$;

create or replace function public.is_super() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.super_users where email = public.me())
$$;

create or replace function public.is_manager_of(b bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.manager_buildings where building_id = b and email = public.me())
$$;

create or replace function public.has_role(b bigint, r text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.members where building_id = b and email = public.me() and role = r)
$$;

-- full management of one building: super user, its manager, or its committee
create or replace function public.can_manage(b bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_super() or public.is_manager_of(b) or public.has_role(b, 'committee')
$$;

-- may read the whole building board: managers + tenants
create or replace function public.can_see_board(b bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.can_manage(b) or public.has_role(b, 'tenant')
$$;

create or replace function public.is_member_any(b bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.can_see_board(b) or public.has_role(b, 'apt_owner')
$$;

-- ---------- narrow data functions for tenants and apartment owners ----------
-- own-apartment payments: month, amount, method, date only (never notes, bank descriptions, references).
-- tenant / apartment owner: only an apartment linked to them, and only the current tenancy. Managers: any apartment.
create or replace function public.apt_payments(b bigint, a int, yr int)
returns table (y int, m int, amount numeric, method text, paid_on date)
language sql stable security definer set search_path = public as $$
  select p.y, p.m, p.amount, p.method, p.paid_on
  from public.payments p
  where p.building_id = b and p.apt = a and p.y = yr
    and (
      public.can_manage(b)
      or (
        exists (select 1 from public.members mm
                where mm.building_id = b and mm.apt = a and mm.email = public.me()
                  and mm.role in ('tenant', 'apt_owner'))
        and exists (select 1 from public.residents r
                    where r.building_id = b and r.key = p.key and coalesce(r.status, '') <> 'עזב')
      )
    )
  order by p.m, p.paid_on
$$;

-- the board a person may see: the whole snapshot for tenants and managers; for an apartment owner who is
-- not also a tenant, only the rows of the apartments they own
create or replace function public.my_snapshot(b bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare s jsonb; apts int[];
begin
  select data into s from public.snapshot where building_id = b;
  if s is null then return null; end if;
  if public.can_see_board(b) then return s; end if;
  select array_agg(distinct apt) into apts from public.members
   where building_id = b and email = public.me() and role = 'apt_owner';
  if apts is null then return null; end if;
  return jsonb_set(s, '{grids}', coalesce((
    select jsonb_object_agg(y.key, (
      select coalesce(jsonb_agg(r), '[]'::jsonb) from jsonb_array_elements(y.value) r where (r ->> 'apt')::int = any(apts)))
    from jsonb_each(s -> 'grids') y), '{}'::jsonb));
end $$;

-- current tenants (names, phones) of the apartments the caller owns
create or replace function public.apt_tenants(b bigint)
returns table (apt int, key text, first_name text, last_name text, first2 text, last2 text, phone1 text, phone2 text, role text)
language sql stable security definer set search_path = public as $$
  select r.apt, r.key, r.first_name, r.last_name, r.first2, r.last2, r.phone1, r.phone2, r.role
  from public.residents r
  where r.building_id = b and coalesce(r.status, '') <> 'עזב'
    and exists (select 1 from public.members mm
                where mm.building_id = b and mm.email = public.me() and mm.role = 'apt_owner' and mm.apt = r.apt)
  order by r.apt
$$;

-- the super user, a buildings manager or a building committee member creates a building;
-- a manager becomes its manager, a committee member becomes its committee
create or replace function public.create_building(nm text) returns bigint
language plpgsql security definer set search_path = public as $$
declare nid bigint; mgr boolean; com boolean;
begin
  mgr := exists (select 1 from public.managers where email = public.me());
  com := exists (select 1 from public.members where email = public.me() and role = 'committee');
  if not (public.is_super() or mgr or com) then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  if nm is null or length(trim(nm)) = 0 then raise exception 'name required'; end if;
  insert into public.buildings (name) values (trim(nm)) returning id into nid;
  if public.is_super() then null;
  elsif mgr then insert into public.manager_buildings (building_id, email) values (nid, public.me());
  else insert into public.members (building_id, email, role) values (nid, public.me(), 'committee');
  end if;
  return nid;
end $$;

-- every function is callable only by logged-in users
do $$
declare f record;
begin
  for f in select p.oid::regprocedure as sig from pg_proc p join pg_namespace n on n.oid = p.pronamespace
           where n.nspname = 'public' and p.proname in
             ('me','is_super','is_manager_of','has_role','can_manage','can_see_board','is_member_any','apt_payments','my_snapshot','apt_tenants','create_building')
  loop
    execute format('revoke all on function %s from public, anon', f.sig);
    execute format('grant execute on function %s to authenticated', f.sig);
  end loop;
end $$;

