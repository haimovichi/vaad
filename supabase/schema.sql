-- ---------- who is calling ----------
create or replace function public.me() returns text
language sql stable set search_path = public as $$ select lower(coalesce(auth.jwt() ->> 'email', '')) $$;

-- the users row of the caller (by login email), null when there is none
create or replace function public.my_uid() returns bigint
language sql stable security definer set search_path = public as $$
  select id from public.users where email = public.me()
$$;

create or replace function public.is_super() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.super_users where email = public.me())
$$;

create or replace function public.is_manager_of(b bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.manager_buildings where building_id = b and email = public.me())
$$;

create or replace function public.has_role(b bigint, r text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.members where building_id = b and user_id = public.my_uid() and role = r)
$$;

-- full management of one building: super user, its manager, or its committee
create or replace function public.can_manage(b bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_super() or public.is_manager_of(b) or public.has_role(b, 'committee')
$$;

-- may read the whole building board: managers + tenants
create or replace function public.can_see_board(b bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.can_manage(b) or public.has_role(b, 'tenant')
$$;

create or replace function public.is_member_any(b bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.can_see_board(b) or public.has_role(b, 'apt_owner')
$$;

-- ---------- narrow data functions for tenants and apartment owners ----------
-- own-apartment payments: month, amount, method, date only (never notes, bank descriptions, references).
-- tenant / apartment owner: only an apartment linked to them, and only the current tenancy. Managers: any apartment.
create or replace function public.apt_payments(b bigint, a int, yr int)
returns table (y int, m int, amount numeric, method text, paid_on date)
language sql stable security definer set search_path = public as $$
  select p.y, p.m, p.amount, p.method, p.paid_on
  from public.payments p
  where p.building_id = b and p.apt = a and p.y = yr
    and (
      public.can_manage(b)
      or (
        exists (select 1 from public.members mm
                where mm.building_id = b and mm.apt = a and mm.user_id = public.my_uid()
                  and mm.role in ('tenant', 'apt_owner'))
        and exists (select 1 from public.residents r
                    where r.building_id = b and r.key = p.key and coalesce(r.status, '') <> 'עזב')
      )
    )
  order by p.m, p.paid_on
$$;

-- the board a person may see: the whole snapshot for tenants and managers; for an apartment owner who is
-- not also a tenant, only the rows of the apartments they own
create or replace function public.my_snapshot(b bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare s jsonb; apts int[];
begin
  select data into s from public.snapshot where building_id = b;
  if s is null then return null; end if;
  if public.can_see_board(b) then return s; end if;
  select array_agg(distinct apt) into apts from public.members
   where building_id = b and user_id = public.my_uid() and role = 'apt_owner';
  if apts is null then return null; end if;
  return jsonb_set(s, '{grids}', coalesce((
    select jsonb_object_agg(y.key, (
      select coalesce(jsonb_agg(r), '[]'::jsonb) from jsonb_array_elements(y.value) r where (r ->> 'apt')::int = any(apts)))
    from jsonb_each(s -> 'grids') y), '{}'::jsonb));
end $$;

-- current tenants (names, phones) of the apartments the caller owns
create or replace function public.apt_tenants(b bigint)
returns table (apt int, key text, first_name text, last_name text, first2 text, last2 text, phone1 text, phone2 text, role text)
language sql stable security definer set search_path = public as $$
  select r.apt, r.key, u1.first_name, u1.last_name, u2.first_name, u2.last_name, u1.phone, u2.phone, r.role
  from public.residents r
  left join public.users u1 on u1.id = r.user_id
  left join public.users u2 on u2.id = r.user2_id
  where r.building_id = b and coalesce(r.status, '') <> 'עזב'
    and exists (select 1 from public.members mm
                where mm.building_id = b and mm.user_id = public.my_uid() and mm.role = 'apt_owner' and mm.apt = r.apt)
  order by r.apt
$$;

-- the super user, a buildings manager or a building committee member creates a building;
-- a manager becomes its manager, a committee member becomes its committee
create or replace function public.create_building(nm text) returns bigint
language plpgsql security definer set search_path = public as $$
declare nid bigint; mgr boolean; com boolean;
begin
  mgr := exists (select 1 from public.managers where email = public.me());
  com := exists (select 1 from public.members where user_id = public.my_uid() and role = 'committee');
  if not (public.is_super() or mgr or com) then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  if nm is null or length(trim(nm)) = 0 then raise exception 'name required'; end if;
  insert into public.buildings (name) values (trim(nm)) returning id into nid;
  if public.is_super() then null;
  elsif mgr then insert into public.manager_buildings (building_id, email) values (nid, public.me());
  else insert into public.members (building_id, user_id, role) values (nid, public.my_uid(), 'committee');
  end if;
  return nid;
end $$;

-- the users row for an email, created (email only) when missing. Granting a role to a person who is not a user yet
-- goes through this: the super user, buildings managers and committee members may call it.
create or replace function public.user_for_email(e text) returns bigint
language plpgsql security definer set search_path = public as $$
declare uid bigint; em text := lower(trim(coalesce(e, '')));
begin
  if not (public.is_super() or exists (select 1 from public.managers where email = public.me())
          or exists (select 1 from public.members where user_id = public.my_uid() and role = 'committee')) then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  if em !~ '^\S+@\S+\.\S+$' then raise exception 'invalid email'; end if;
  select id into uid from public.users where email = em;
  if uid is null then insert into public.users (email) values (em) returning id into uid; end if;
  return uid;
end $$;

-- ---------- bank matching (same rules as lib/match.js) ----------
-- the payer part of a bank description: quotes dropped, leading transfer words, account text and digits removed
create or replace function public.payer_key(descr text) returns text
language sql immutable set search_path = public as $$
  select btrim(regexp_replace(regexp_replace(regexp_replace(regexp_replace(
    btrim(regexp_replace(regexp_replace(coalesce(descr, ''), '["''׳״]', '', 'g'), '\s+', ' ', 'g')),
    '^(העברה|הוק)\s+', ''), 'חשבון.*$', ''), '\d[\d-]*', '', 'g'), '\s+', ' ', 'g'))
$$;

-- Match one bank credit to an apartment of building b. Order: learned alias, account number, "דירה N" hint,
-- full name, last name only. sure = false when the match is a guess (last name only, or a name or account
-- shared by several apartments: then apt is null and candidates lists them). Managers of the building only.
create or replace function public.match_payer(b bigint, descr text)
returns table (apt int, how text, sure boolean, candidates int[])
language plpgsql stable security definer set search_path = public as $$
declare
  k text; al int; acc text; hint int; txt text; full_apts int[]; last_apts int[];
begin
  if not public.can_manage(b) then raise exception 'not allowed' using errcode = '42501'; end if;
  k := public.payer_key(descr);

  select (m.value ->> k)::int into al from public.meta m where m.building_id = b and m.name = 'aliases';
  if al is not null then return query select al, 'זכור מתיקון קודם'::text, true, '{}'::int[]; return; end if;

  acc := regexp_replace(regexp_replace(substring(coalesce(descr, '') from '\d{2,3}-\d{3}-\d{4}-(\d{5,9})'), '\D', '', 'g'), '^0+', '');
  if acc is not null and length(acc) >= 5 then
    select coalesce(array_agg(distinct x.a order by x.a), '{}') into full_apts from (
      select o.apt a from public.owners o join public.bank_accounts ba on ba.user_id = o.user_id
       where o.building_id = b and regexp_replace(regexp_replace(ba.account, '\D', '', 'g'), '^0+', '') = acc
      union
      select r.apt from public.residents r join public.bank_accounts ba on ba.user_id in (r.user_id, r.user2_id)
       where r.building_id = b and regexp_replace(regexp_replace(ba.account, '\D', '', 'g'), '^0+', '') = acc) x;
    if cardinality(full_apts) = 1 then return query select full_apts[1], 'מספר חשבון'::text, true, '{}'::int[]; return; end if;
    if cardinality(full_apts) > 1 then return query select null::int, 'כמה דירות לאותו חשבון'::text, false, full_apts; return; end if;
  end if;

  hint := substring(coalesce(descr, '') from 'דירה\s*(\d{1,2})')::int;
  if hint is not null and exists (select 1 from public.apartments a where a.building_id = b and a.apt = hint) then
    return query select hint, 'הערה בהעברה'::text, true, '{}'::int[]; return;
  end if;

  txt := btrim(regexp_replace(regexp_replace(coalesce(descr, ''), '["''׳״]', '', 'g'), '\s+', ' ', 'g'));
  select coalesce(array_agg(distinct p.a order by p.a) filter (where p.full_hit), '{}'),
         coalesce(array_agg(distinct p.a order by p.a) filter (where not p.full_hit), '{}')
    into full_apts, last_apts
  from (
    select q.a, q.fn <> '' and position(q.fn in txt) > 0 as full_hit
    from (
      select r.apt a, u.first_name fn, u.last_name ln
        from public.residents r join public.users u on u.id in (r.user_id, r.user2_id)
       where r.building_id = b and coalesce(r.status, '') <> 'עזב'
      union all
      select o.apt, u.first_name, u.last_name
        from public.owners o join public.users u on u.id = o.user_id
       where o.building_id = b) raw,
    lateral (select raw.a, btrim(regexp_replace(regexp_replace(coalesce(raw.fn, ''), '["''׳״]', '', 'g'), '\s+', ' ', 'g')) fn,
                    btrim(regexp_replace(regexp_replace(coalesce(raw.ln, ''), '["''׳״]', '', 'g'), '\s+', ' ', 'g')) ln) q
    where length(q.ln) >= 3 and position(q.ln in txt) > 0) p;
  -- an apartment that has a full-name hit is not also a last-name-only candidate
  last_apts := array(select x from unnest(last_apts) x where x <> all(full_apts));

  if cardinality(full_apts) = 1 then return query select full_apts[1], 'שם מלא'::text, true, '{}'::int[]; return; end if;
  if cardinality(full_apts) > 1 then return query select null::int, 'כמה דירות לאותו שם'::text, false, full_apts; return; end if;
  if cardinality(last_apts) = 1 then return query select last_apts[1], 'שם משפחה בלבד'::text, false, '{}'::int[]; return; end if;
  if cardinality(last_apts) > 1 then return query select null::int, 'כמה דירות לאותו שם'::text, false, last_apts; return; end if;
  return query select null::int, 'לא זוהה'::text, false, '{}'::int[];
end $$;

-- ---------- splitting a credit over months (same rules as allocate() in lib/match.js) ----------
-- What an apartment owes for a month: the year's base tariff, replaced by the apartment's own tariff,
-- plus one-off surcharges of that month. Internal helper: not callable from the app.
create or replace function public.tariff_due(b bigint, a int, y int, m int) returns numeric
language sql stable security definer set search_path = public as $$
  select coalesce(
           (select t.amount from public.tariffs t where t.building_id = b and t.year = y and coalesce(t.month, 0) = 0 and t.apt = a order by t.id limit 1),
           (select t.amount from public.tariffs t where t.building_id = b and t.year = y and coalesce(t.month, 0) = 0 and coalesce(t.apt, 0) = 0 order by t.id limit 1),
           0)
       + coalesce((select sum(t.amount) from public.tariffs t
                    where t.building_id = b and t.year = y and t.month = m and coalesce(t.apt, 0) in (0, a)), 0)
$$;

-- The tenancy of apartment a covering month index tx (year*12 + month-1): the one whose entry..exit months contain it,
-- else the apartment's latest. Internal helper: not callable from the app.
create or replace function public.tenancy_at(b bigint, a int, tx int) returns table (key text, f int, t int)
language sql stable security definer set search_path = public as $$
  select x.key, x.f, x.t from (
    select r.key, r.id,
           case when coalesce(r.entry_year, 0) <> 0 then r.entry_year * 12 + coalesce(nullif(r.entry_month, 0), 1) - 1 else 2022 * 12 + 5 end f,
           case when r.status = 'עזב' and coalesce(r.exit_year, 0) <> 0 then r.exit_year * 12 + coalesce(nullif(r.exit_month, 0), 12) - 1 else 2147483647 end t
      from public.residents r where r.building_id = b and r.apt = a) x
  order by not (x.f <= tx and tx <= x.t), case when x.f <= tx and tx <= x.t then x.id else -x.id end
  limit 1
$$;

-- Propose how to split a credit of amt, paid on on_date for apartment a, over months: the transaction month,
-- then the oldest unpaid months of the last 6 months, then upcoming months; what is left (nothing due anywhere)
-- is parked on the transaction month. The tenancy is the one covering the date (else the apartment's latest);
-- its payments form one pool that fills the oldest month first. `already` = amounts proposed for the same
-- tenancy earlier in the same import, not saved yet. No rows when the apartment has no tenancy. Managers only.
create or replace function public.split_payment(b bigint, a int, amt numeric, on_date date, already numeric default 0)
returns table (yr int, mo int, part numeric)
language plpgsql stable security definer set search_path = public as $$
declare
  start_i constant int := 2022 * 12 + 5;     -- collection starts June 2022
  tx int; t_key text; t_from int; t_to int; pool numeric;
begin
  if not public.can_manage(b) then raise exception 'not allowed' using errcode = '42501'; end if;
  if amt is null or amt <= 0 then raise exception 'amount must be positive'; end if;
  tx := extract(year from on_date)::int * 12 + extract(month from on_date)::int - 1;

  select ty.key, ty.f, ty.t into t_key, t_from, t_to from public.tenancy_at(b, a, tx) ty;
  if t_key is null then return; end if;

  select coalesce(sum(p.amount), 0) + coalesce(already, 0) into pool from public.payments p where p.building_id = b and p.key = t_key;

  return query
  with months as (
    select i, public.tariff_due(b, a, i / 12, i % 12 + 1) due
      from generate_series(greatest(start_i, t_from), tx + 24) i where i <= t_to),
  cov as (select i, due, least(due, greatest(0, pool - (sum(due) over (order by i) - due))) paid from months),
  cand as (
    select i, due - paid r, case when i = tx then 0 when i < tx then i - (tx - 6) + 1 else 6 + (i - tx) end ord
      from cov where due - paid > 0 and i between tx - 6 and tx + 24),
  takes as (
    select i, ord, least(r, greatest(0, amt - (sum(r) over (order by ord) - r))) take from cand),
  parts as (
    select i, ord, take from takes where take > 0
    union all
    select tx, 1000, amt - (select coalesce(sum(take), 0) from takes))
  select p.i / 12, p.i % 12 + 1, p.take from parts p where p.take > 0 order by p.ord;
end $$;

-- ---------- credits the system cannot place with certainty wait for the committee ----------
-- Save bank credits as pending payments: no apartment, with an automatic comment suggesting where each belongs
-- (match_payer's answer). credits = [{key, refKey, ref, date, amount, desc}, ...]; amount > 0. A bank row that is
-- already recorded (bank key or reference seen, or already saved as a payment or as pending) is skipped, so saving
-- twice adds nothing. The rows are marked seen, so the next import does not list them again. Returns how many were
-- added. Managers of the building only.
create or replace function public.save_pending_credits(b bigint, credits jsonb) returns int
language plpgsql security definer set search_path = public as $$
declare
  c jsonb; k text; rk text; amt numeric; d date; m record; note text; cmt text; added int := 0;
begin
  if not public.can_manage(b) then raise exception 'not allowed' using errcode = '42501'; end if;
  if jsonb_typeof(credits) is distinct from 'array' then raise exception 'credits must be a list'; end if;
  for c in select * from jsonb_array_elements(credits) loop
    k := nullif(c ->> 'key', ''); rk := nullif(c ->> 'refKey', '');
    amt := (c ->> 'amount')::numeric; d := (c ->> 'date')::date;
    if k is null or d is null or amt is null or amt <= 0 then raise exception 'each credit needs key, date and a positive amount'; end if;
    if exists (select 1 from public.meta s where s.building_id = b and s.name = 'bankSeen' and s.value ? k)
       or exists (select 1 from public.meta s where s.building_id = b and s.name = 'ignored' and s.value ? k)
       or (rk is not null and exists (select 1 from public.meta s where s.building_id = b and s.name = 'refSeen' and s.value ? rk))
       or exists (select 1 from public.payments p where p.building_id = b and p.tx_key = k)
       or exists (select 1 from public.pending_payments p where p.building_id = b and p.tx_key = k)
    then continue; end if;

    select * into m from public.match_payer(b, coalesce(c ->> 'desc', ''));
    cmt := case
      when m.how = 'לא זוהה' then 'לא זוהה'
      when m.apt is not null then 'הצעה: דירה ' || m.apt || ' (' || m.how || ')'
      else 'דירות אפשריות: ' || array_to_string(m.candidates, ', ') || ' (' || m.how || ')'
    end;
    note := 'בנק: ' || left(coalesce(c ->> 'desc', ''), 60);
    insert into public.pending_payments (building_id, y, m, amount, method, paid_on, note, ref, tx_key, auto_comment, payer)
    values (b, extract(year from d)::int, extract(month from d)::int, amt, 'העברה בנקאית', d, note, nullif(c ->> 'ref', ''), k, cmt, public.payer_key(c ->> 'desc'));
    insert into public.meta (building_id, name, value) values (b, 'bankSeen', jsonb_build_object(k, true))
      on conflict (building_id, name) do update set value = public.meta.value || jsonb_build_object(k, true);
    if rk is not null then
      insert into public.meta (building_id, name, value) values (b, 'refSeen', jsonb_build_object(rk, true))
        on conflict (building_id, name) do update set value = public.meta.value || jsonb_build_object(rk, true);
    end if;
    added := added + 1;
  end loop;
  return added;
end $$;

-- Approve a pending credit for apartment a (the suggested one, or another): it becomes normal payments split over
-- months like split_payment proposes, on the tenancy of that apartment, and the pending row is removed.
-- learn = remember this payer for next time (an alias). Returns the number of payment rows added. Managers only.
create or replace function public.approve_pending(pid bigint, a int, learn boolean default false) returns int
language plpgsql security definer set search_path = public as $$
declare pp record; d date; tk text; n int;
begin
  select * into pp from public.pending_payments where id = pid;
  if not found or not public.can_manage(pp.building_id) then raise exception 'not allowed' using errcode = '42501'; end if;
  if not exists (select 1 from public.apartments x where x.building_id = pp.building_id and x.apt = a) then raise exception 'no such apartment'; end if;
  d := coalesce(pp.paid_on, make_date(pp.y, pp.m, 1));
  select ty.key into tk from public.tenancy_at(pp.building_id, a, extract(year from d)::int * 12 + extract(month from d)::int - 1) ty;
  if tk is null then raise exception 'the apartment has no tenant record'; end if;
  insert into public.payments (building_id, key, apt, y, m, amount, method, paid_on, note, ref, src, tx_key)
    select pp.building_id, tk, a, s.yr, s.mo, s.part, pp.method, pp.paid_on, pp.note, pp.ref, 'bank', pp.tx_key
      from public.split_payment(pp.building_id, a, pp.amount, d) s;
  get diagnostics n = row_count;
  if learn and coalesce(pp.payer, '') <> '' then
    insert into public.meta (building_id, name, value) values (pp.building_id, 'aliases', jsonb_build_object(pp.payer, a))
      on conflict (building_id, name) do update set value = public.meta.value || jsonb_build_object(pp.payer, a);
  end if;
  delete from public.pending_payments where id = pid;
  return n;
end $$;

-- A pending credit that is not a dues payment: ignored, like an ignored row of the bank import. Managers only.
create or replace function public.ignore_pending(pid bigint) returns void
language plpgsql security definer set search_path = public as $$
declare pp record;
begin
  select * into pp from public.pending_payments where id = pid;
  if not found or not public.can_manage(pp.building_id) then raise exception 'not allowed' using errcode = '42501'; end if;
  if pp.tx_key is not null then
    insert into public.meta (building_id, name, value) values (pp.building_id, 'ignored', jsonb_build_object(pp.tx_key, true))
      on conflict (building_id, name) do update set value = public.meta.value || jsonb_build_object(pp.tx_key, true);
  end if;
  delete from public.pending_payments where id = pid;
end $$;

-- ---------- the bank import on the server ----------
-- Proposals for a list of bank credits, in the order given (the caller sorts them by date): for each, the apartment
-- match_payer finds (or the apartment forced by the caller: "apt" in the credit), its reason, certainty and candidates,
-- the tenancy, and the split over months from split_payment. Credits proposed earlier in the same list count as
-- paid for their tenancy. credits = [{key, date, desc, amount, apt?}, ...]. Managers of the building only.
create or replace function public.propose_credits(b bigint, credits jsonb) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  c jsonb; res jsonb := '[]'; pool jsonb := '{}'; m record; ap int; d date; amt numeric; tk text; parts jsonb; how text; sure boolean; cands int[];
begin
  if not public.can_manage(b) then raise exception 'not allowed' using errcode = '42501'; end if;
  if jsonb_typeof(credits) is distinct from 'array' then raise exception 'credits must be a list'; end if;
  for c in select * from jsonb_array_elements(credits) loop
    d := (c ->> 'date')::date; amt := (c ->> 'amount')::numeric;
    if d is null or amt is null or amt <= 0 then raise exception 'each credit needs a date and a positive amount'; end if;
    ap := nullif(c ->> 'apt', '')::int;
    if ap is not null then how := 'נבחרה ידנית'; sure := true; cands := '{}';
    else
      select * into m from public.match_payer(b, coalesce(c ->> 'desc', ''));
      ap := m.apt; how := m.how; sure := m.sure; cands := m.candidates;
    end if;
    tk := null; parts := '[]';
    if ap is not null then
      select ty.key into tk from public.tenancy_at(b, ap, extract(year from d)::int * 12 + extract(month from d)::int - 1) ty;
      if tk is not null then
        select coalesce(jsonb_agg(jsonb_build_object('y', s.yr, 'm', s.mo, 'amount', s.part) order by s.n), '[]') into parts
          from public.split_payment(b, ap, amt, d, coalesce((pool ->> tk)::numeric, 0)) with ordinality s(yr, mo, part, n);
        pool := pool || jsonb_build_object(tk, coalesce((pool ->> tk)::numeric, 0) + amt);
      end if;
    end if;
    res := res || jsonb_build_array(jsonb_build_object('key', c ->> 'key', 'apt', ap, 'how', how, 'sure', sure,
             'candidates', to_jsonb(cands), 'tenancy', tk, 'allocations', parts));
  end loop;
  return res;
end $$;

-- Save the treasurer's decisions on a bank import, all or nothing (one transaction): items = [{key, refKey, ref, date,
-- desc, amount, apt?, allocations?: [{y, m, amount}], learn?, ignore?}, ...].
--   ignore         : the row is ignored from now on
--   apt + parts    : normal payments on that apartment's tenancy (the parts must add up to the amount); with learn,
--                    the payer is remembered as an alias for that apartment
--   no apartment   : saved as a pending credit with a suggestion (save_pending_credits)
-- A bank row that is already recorded is skipped, so saving twice adds nothing. Returns {added, pending, ignored}.
-- Managers of the building only.
create or replace function public.save_import(b bigint, items jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  it jsonb; k text; rk text; amt numeric; d date; ap int; tk text; a jsonb; total numeric; pend jsonb := '[]';
  added int := 0; ign int := 0; pcount int := 0;
begin
  if not public.can_manage(b) then raise exception 'not allowed' using errcode = '42501'; end if;
  if jsonb_typeof(items) is distinct from 'array' then raise exception 'items must be a list'; end if;
  for it in select * from jsonb_array_elements(items) loop
    k := nullif(it ->> 'key', ''); rk := nullif(it ->> 'refKey', '');
    if k is null then raise exception 'each row needs a key'; end if;
    if exists (select 1 from public.meta s where s.building_id = b and s.name in ('bankSeen', 'ignored') and s.value ? k)
       or exists (select 1 from public.payments p where p.building_id = b and p.tx_key = k)
       or exists (select 1 from public.pending_payments p where p.building_id = b and p.tx_key = k)
    then continue; end if;

    if coalesce((it ->> 'ignore')::boolean, false) then
      insert into public.meta (building_id, name, value) values (b, 'ignored', jsonb_build_object(k, true))
        on conflict (building_id, name) do update set value = public.meta.value || jsonb_build_object(k, true);
      ign := ign + 1; continue;
    end if;

    ap := nullif(it ->> 'apt', '')::int;
    if ap is null then pend := pend || jsonb_build_array(it); continue; end if;

    d := (it ->> 'date')::date; amt := (it ->> 'amount')::numeric;
    if d is null or amt is null or amt <= 0 then raise exception 'each credit needs a date and a positive amount'; end if;
    if jsonb_typeof(it -> 'allocations') is distinct from 'array' or jsonb_array_length(it -> 'allocations') = 0 then raise exception 'missing split over months'; end if;
    select coalesce(sum((x ->> 'amount')::numeric), 0) into total from jsonb_array_elements(it -> 'allocations') x;
    if abs(total - amt) > 0.01 then raise exception 'the split over months does not match the amount (%)', k; end if;
    if not exists (select 1 from public.apartments x where x.building_id = b and x.apt = ap) then raise exception 'no such apartment'; end if;
    select ty.key into tk from public.tenancy_at(b, ap, extract(year from d)::int * 12 + extract(month from d)::int - 1) ty;
    if tk is null then raise exception 'the apartment has no tenant record'; end if;
    for a in select * from jsonb_array_elements(it -> 'allocations') loop
      if (a ->> 'm')::int not between 1 and 12 or (a ->> 'y')::int not between 2000 and 2100 or (a ->> 'amount')::numeric <= 0 then raise exception 'bad month in the split'; end if;
      insert into public.payments (building_id, key, apt, y, m, amount, method, paid_on, note, ref, src, tx_key)
      values (b, tk, ap, (a ->> 'y')::int, (a ->> 'm')::int, (a ->> 'amount')::numeric, 'העברה בנקאית', d,
              'בנק: ' || left(coalesce(it ->> 'desc', ''), 60), nullif(it ->> 'ref', ''), 'bank', k);
    end loop;
    insert into public.meta (building_id, name, value) values (b, 'bankSeen', jsonb_build_object(k, true))
      on conflict (building_id, name) do update set value = public.meta.value || jsonb_build_object(k, true);
    if rk is not null then
      insert into public.meta (building_id, name, value) values (b, 'refSeen', jsonb_build_object(rk, true))
        on conflict (building_id, name) do update set value = public.meta.value || jsonb_build_object(rk, true);
    end if;
    if coalesce((it ->> 'learn')::boolean, false) and public.payer_key(it ->> 'desc') <> '' then
      insert into public.meta (building_id, name, value) values (b, 'aliases', jsonb_build_object(public.payer_key(it ->> 'desc'), ap))
        on conflict (building_id, name) do update set value = public.meta.value || jsonb_build_object(public.payer_key(it ->> 'desc'), ap);
    end if;
    added := added + 1;
  end loop;
  if jsonb_array_length(pend) > 0 then pcount := public.save_pending_credits(b, pend); end if;
  return jsonb_build_object('added', added, 'pending', pcount, 'ignored', ign);
end $$;

