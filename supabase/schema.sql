-- ועד הבית — schema + role-based security (multi-building, five roles).
-- Run in Supabase: SQL Editor -> New query -> paste -> Run. Safe to re-run (idempotent).
-- Upgrading from the earlier owner/admin/tenant version? Run supabase/migrate-roles.sql first, then this file.
--
-- ROLES
--   super user        : exactly one person, set only in the SQL editor (table super_users). Can do anything, in every building.
--   buildings manager : table managers + manager_buildings. Manages the buildings assigned to them and can create new ones.
--   building committee: members.role = 'committee'. Manages one building (bank import, payments, tenants, backup...).
--   tenant            : members.role = 'tenant' (+ apt). Sees the building board; payment details only for their own apartment.
--   apartment owner   : members.role = 'apt_owner' (+ apt). Sees only their apartments: status, the current tenant's
--                       payments with dates, and the tenant's name and phone.
-- A person can hold any mix of roles; they combine (union of what each allows).
--
-- PEOPLE AND ROLES ARE SEPARATE
--   users   : one row per person (first/last name, email, full phone). The email is optional: a tenant
--             without an email is still a user, he just can't log in. Only the super user edits users; the staff of a
--             building (committee, managers) read the users of their building.
--   bank_accounts : a person's bank accounts (none, one or several), linked to the user. Same read/write rules as users.
--   members : the roles (user, building, role, apartment). One user can hold many rows, even in one building
--             (owner of three apartments, tenant in one of them, committee member), and in other buildings too.
--   residents / owners point at users (user_id, and user2_id for a second person on a tenancy).
--
-- WHO CAN GRANT WHAT (enforced on public.members)
--   super user: any building, committee/tenant/apt_owner (and managers, in the app)
--   manager   : committee/tenant/apt_owner in the buildings they manage
--   committee : tenant/apt_owner in their own building

create table if not exists public.buildings (
  id   bigint generated by default as identity primary key,
  name text not null
);

-- platform level --------------------------------------------------------------------------------
create table if not exists public.super_users (
  email text primary key check (email = lower(email))
);
create unique index if not exists super_users_one_row on public.super_users ((true));  -- at most one super user, ever

create table if not exists public.managers (
  email text primary key check (email = lower(email))
);
create table if not exists public.manager_buildings (
  building_id bigint not null references public.buildings(id) on delete cascade,
  email text not null references public.managers(email) on delete cascade,
  primary key (building_id, email)
);

-- building level --------------------------------------------------------------------------------
create table if not exists public.users (
  id bigint generated always as identity primary key,
  email text unique check (email is null or email = lower(email)),
  first_name text, last_name text,
  phone text,            -- full phone number
  created_at timestamptz not null default now()
);

-- a person may have no bank account, one, or several (they are used to recognise who paid in a bank file)
