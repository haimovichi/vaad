-- building data: whoever can manage the building reads and writes it
do $$
declare t text;
begin
  foreach t in array array['apartments','residents','owners','tariffs','payments','expenses','meta'] loop
    execute format($p$create policy manage_all on public.%I for all to authenticated using (public.can_manage(building_id)) with check (public.can_manage(building_id))$p$, t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;

-- buildings: you see the ones you belong to; super user sees all. The name is the address and never changes. Create/delete: functions / SQL editor only
create policy member_read  on public.buildings for select to authenticated using (public.is_super() or public.is_manager_of(id) or public.is_member_any(id));
grant select, update on public.buildings to authenticated;

-- managers and their buildings: a manager reads their own rows; only the super user writes
create policy self_read  on public.managers for select to authenticated using (email = public.me());
create policy super_all  on public.managers for all    to authenticated using (public.is_super()) with check (public.is_super());
create policy self_read  on public.manager_buildings for select to authenticated using (email = public.me());
create policy super_all  on public.manager_buildings for all    to authenticated using (public.is_super()) with check (public.is_super());
grant select, insert, update, delete on public.managers, public.manager_buildings to authenticated;

-- members: everyone reads their own rows; managers of a building read all its rows;
-- granting follows the hierarchy: super (any) > manager (any role in their buildings) > committee (tenant, apt_owner only)
create policy own_rows  on public.members for select to authenticated using (email = public.me() or public.can_manage(building_id));
create policy grant_roles on public.members for all to authenticated
  using      (public.is_super() or public.is_manager_of(building_id) or (public.has_role(building_id, 'committee') and role in ('tenant', 'apt_owner')))
  with check (public.is_super() or public.is_manager_of(building_id) or (public.has_role(building_id, 'committee') and role in ('tenant', 'apt_owner')));
grant select, insert, update, delete on public.members to authenticated;

-- snapshot: whoever may see the board reads it (apartment owners use my_snapshot()); whoever manages the building writes it
create policy board_read   on public.snapshot for select to authenticated using (public.can_see_board(building_id));
create policy manage_write on public.snapshot for all    to authenticated using (public.can_manage(building_id)) with check (public.can_manage(building_id));
grant select, insert, update, delete on public.snapshot to authenticated;

grant usage on all sequences in schema public to authenticated;
